const LanguageContext = createContext<LanguageContextType | undefined>(undefined)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>('en')
  const [mounted, setMounted] = useState(false)

  useEffect(() => {
    // Load saved language on mount
    const saved = localStorage.getItem('app_language') as Language
    if (saved && (saved === 'en' || saved === 'hi')) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLanguage(saved)
    }
    setMounted(true)
  }, [])

  const handleSetLanguage = (lang: Language) => {
    setLanguage(lang)
    localStorage.setItem('app_language', lang)
  }

  const t = (key: string): string => {
    const entry = translations[key]
    if (entry) {
      const translated = mounted ? (entry[language] || entry.en) : entry.en
      if (translated) return translated
    }

    // Development logging for missing keys
    if (process.env.NODE_ENV === 'development') {
      console.warn(`[i18n AUDIT] Missing translation key: "${key}" for language "${language}"`)
    }

    // Emergency fallback to prevent raw keys like "orders.col_amount" showing in UI
    const parts = key.split('.')
    const lastPart = parts[parts.length - 1] || key
    return lastPart.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase())
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage: handleSetLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}
